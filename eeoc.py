def get_eeoc_data(business_name):
    """Get EEOC discrimination case data for a business"""
    key = business_name.lower().strip()
    
    # Direct match
    if key in EEOC_DATA:
        return {"found": True, **EEOC_DATA[key]}
    
    # Partial match
    for company, data in EEOC_DATA.items():
        if company in key or key in company:
            return {"found": True, **data}
    
    return {"found": False}
